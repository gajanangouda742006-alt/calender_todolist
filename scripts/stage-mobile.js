const fs = require('node:fs');
const path = require('node:path');
const { build } = require('esbuild');

const root = path.resolve(__dirname, '..');
const webDir = path.join(root, 'www');
const marker = path.join(webDir, '.sahra-mobile-generated');
const apiBase = process.env.SAHRA_API_BASE_URL;

if (!apiBase) {
  throw new Error('Set SAHRA_API_BASE_URL to the HTTPS origin of the deployed Sahra API before staging a mobile build.');
}

let apiOrigin;
try {
  const parsed = new URL(apiBase);
  if (
    parsed.protocol !== 'https:' ||
    parsed.username ||
    parsed.password ||
    parsed.pathname !== '/' ||
    parsed.search ||
    parsed.hash
  ) {
    throw new Error();
  }
  apiOrigin = parsed.origin;
} catch {
  throw new Error('SAHRA_API_BASE_URL must be a valid HTTPS origin without credentials, path, query, or fragment.');
}

if (fs.existsSync(webDir)) {
  if (!fs.existsSync(marker)) {
    throw new Error('Refusing to replace existing www directory without the Sahra-generated marker.');
  }
  fs.rmSync(webDir, { recursive: true });
}

fs.mkdirSync(webDir, { recursive: true });
fs.writeFileSync(marker, 'Generated by npm run mobile:stage.\n');

for (const entry of ['style.css', 'menubars.png', 'mic.png']) {
  fs.copyFileSync(path.join(root, entry), path.join(webDir, entry));
}
for (const directory of ['images']) {
  fs.cpSync(path.join(root, directory), path.join(webDir, directory), { recursive: true });
}

const config = [
  `window.SAHRA_API_BASE_URL = ${JSON.stringify(apiOrigin)};`,
  'window.SAHRA_IS_NATIVE = true;',
  `document.documentElement.dataset.sahraNative = 'true';`,
  '',
].join('\n');
fs.writeFileSync(path.join(webDir, 'app-config.js'), config);

const indexHtml = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
if (!indexHtml.includes('<script type="module" src="./app.js"></script>')) {
  throw new Error('Could not locate the application entry script in index.html.');
}
fs.writeFileSync(
  path.join(webDir, 'index.html'),
  indexHtml.replace(
    '<script type="module" src="./app.js"></script>',
    '<script type="module" src="./mobile-entry.js"></script>'
  )
);

const loginHtml = fs.readFileSync(path.join(root, 'frontend', 'login.html'), 'utf8');
if (!loginHtml.includes('<script src="/app-config.js"></script>')) {
  throw new Error('Could not locate the login app configuration script.');
}
fs.writeFileSync(
  path.join(webDir, 'login.html'),
  loginHtml.replace(
    '<script src="/app-config.js"></script>',
    '<script src="./app-config.js"></script>\n    <script type="module" src="./mobile-login.js"></script>'
  )
);

async function bundleEntries() {
  await Promise.all([
    build({
      entryPoints: [path.join(__dirname, 'mobile-entry.js')],
      bundle: true,
      format: 'esm',
      target: 'es2022',
      outfile: path.join(webDir, 'mobile-entry.js'),
    }),
    build({
      entryPoints: [path.join(__dirname, 'mobile-login.js')],
      bundle: true,
      format: 'esm',
      target: 'es2022',
      outfile: path.join(webDir, 'mobile-login.js'),
    }),
  ]);
}

bundleEntries().then(() => {
  console.log(`Mobile client staged in ${webDir} for API ${apiOrigin}`);
}).catch((error) => {
  console.error('Mobile client staging failed:', error);
  process.exitCode = 1;
});
