const fs = require('node:fs');
const path = require('node:path');
const { build } = require('esbuild');

const root = path.resolve(__dirname, '..');
const webDir = path.join(root, 'www');
const marker = path.join(webDir, '.sahra-mobile-generated');
const apiBase = process.env.SAHRA_API_BASE_URL;

if (!apiBase) {
  throw new Error('Set SAHRA_API_BASE_URL to the HTTPS origin of the deployed DaySync API before staging a mobile build.');
}

let apiOrigin;
try {
  const parsed = new URL(apiBase);
  if (
    parsed.protocol !== 'https:' ||
    parsed.username ||
    parsed.password ||
    parsed.pathname !== '/' ||
    parsed.search ||
    parsed.hash
  ) {
    throw new Error();
  }
  apiOrigin = parsed.origin;
} catch {
  throw new Error('SAHRA_API_BASE_URL must be a valid HTTPS origin without credentials, path, query, or fragment.');
}

// Preserve generated-www assets as a fallback when a source asset is stored
// only in the current www output. Some existing DaySync projects keep the logo,
// menu icons and intro video there rather than duplicated at the project root.
const fallbackDir = path.join(root, '.daysync-stage-fallback');
if (fs.existsSync(fallbackDir)) fs.rmSync(fallbackDir, { recursive: true, force: true });
fs.mkdirSync(fallbackDir, { recursive: true });
for (const relative of ['menubars.png', 'mic.png', 'images', 'images/DaySync.png', 'assets/app-intro.mp4']) {
  const rootSource = path.join(root, relative);
  const existingWebSource = path.join(webDir, relative);
  if (!fs.existsSync(rootSource) && fs.existsSync(existingWebSource)) {
    const fallbackTarget = path.join(fallbackDir, relative);
    fs.mkdirSync(path.dirname(fallbackTarget), { recursive: true });
    fs.cpSync(existingWebSource, fallbackTarget, { recursive: true });
  }
}

if (fs.existsSync(webDir)) {
  if (!fs.existsSync(marker)) {
    fs.rmSync(fallbackDir, { recursive: true, force: true });
    throw new Error('Refusing to replace existing www directory without the Sahra-generated marker.');
  }
  fs.rmSync(webDir, { recursive: true });
}

fs.mkdirSync(webDir, { recursive: true });
fs.writeFileSync(marker, 'Generated by npm run mobile:stage.\n');

function copyStageSource(relative, destination = relative, required = true) {
  const primary = path.join(root, relative);
  const fallback = path.join(fallbackDir, relative);
  const source = fs.existsSync(primary) ? primary : (fs.existsSync(fallback) ? fallback : null);
  if (!source) {
    if (required) throw new Error(`Missing mobile staging asset: ${relative}. Place it in the project root or the existing generated www folder.`);
    return false;
  }
  const target = path.join(webDir, destination);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.cpSync(source, target, { recursive: true });
  return true;
}

copyStageSource('style.css');
copyStageSource('goal-achievements-3d.css', 'goal-achievements-3d.css', false);
copyStageSource('menubars.png');
copyStageSource('mic.png');
copyStageSource('images');
copyStageSource('assets/app-intro.mp4');
copyStageSource('images/DaySync.png', 'assets/intro-poster.png');
fs.rmSync(fallbackDir, { recursive: true, force: true });

const config = [
  `window.SAHRA_API_BASE_URL = ${JSON.stringify(apiOrigin)};`,
  'window.SAHRA_IS_NATIVE = true;',
  `document.documentElement.dataset.sahraNative = 'true';`,
  '',
].join('\n');
fs.writeFileSync(path.join(webDir, 'app-config.js'), config);

const indexHtml = fs.readFileSync(path.join(root, 'index.html'), 'utf8');

const appScriptMatch = indexHtml.match(
  /<script\b(?=[^>]*\btype=["']module["'])(?=[^>]*\bsrc=["']\.\/(?:app|web-app)\.js(?:\?[^"']*)?["'])[^>]*><\/script>/i
);

if (!appScriptMatch) {
  throw new Error('Could not locate the application entry script in index.html.');
}

const appScript = appScriptMatch[0];

fs.writeFileSync(
  path.join(webDir, 'index.html'),
  indexHtml.replace(
    appScript,
    '<script type="module" src="./mobile-entry.js"></script>'
  )
);

const loginHtml = fs.readFileSync(path.join(root, 'frontend', 'login.html'), 'utf8');
if (!loginHtml.includes('<script src="/app-config.js"></script>')) {
  throw new Error('Could not locate the login app configuration script.');
}
fs.writeFileSync(
  path.join(webDir, 'login.html'),
  loginHtml.replace(
    '<script src="/app-config.js"></script>',
    '<script src="./app-config.js"></script>\n    <script type="module" src="./mobile-login.js"></script>'
  )
);

async function bundleEntries() {
  await Promise.all([
    build({
      entryPoints: [path.join(__dirname, 'mobile-entry.js')],
      bundle: true,
      format: 'esm',
      target: 'es2022',
      outfile: path.join(webDir, 'mobile-entry.js'),
    }),
    build({
      entryPoints: [path.join(__dirname, 'mobile-login.js')],
      bundle: true,
      format: 'esm',
      target: 'es2022',
      outfile: path.join(webDir, 'mobile-login.js'),
    }),
  ]);
}

bundleEntries().then(() => {
  console.log(`Mobile client staged in ${webDir} for API ${apiOrigin}`);
}).catch((error) => {
  console.error('Mobile client staging failed:', error);
  process.exitCode = 1;
});
